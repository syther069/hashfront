// Regenerates src/abi.ts from Foundry build artifacts. Run after `forge build` whenever a contract interface changes.
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const out = path.resolve(here, "../../../contracts/out");

const sources: Array<[exportName: string, artifact: string]> = [
  ["releaseGateAbi", "ReleaseGate.sol/ReleaseGate.json"],
  ["siteRegistryAbi", "ITapeOut.sol/ISiteRegistry.json"],
  ["processorAbi", "ITapeOut.sol/ITapeOutProcessor.json"],
];

let body = "// Generated by scripts/sync-abi.ts from contracts/out. Do not edit by hand.\n\n";
for (const [name, artifact] of sources) {
  const json = JSON.parse(await readFile(path.join(out, artifact), "utf8")) as { abi: unknown };
  body += `export const ${name} = ${JSON.stringify(json.abi, null, 2)} as const;\n\n`;
}

const target = path.resolve(here, "../src/abi.ts");
await writeFile(target, body.trimEnd() + "\n");
console.log(`wrote ${path.relative(process.cwd(), target)}`);
